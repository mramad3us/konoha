export function textWidth(text: string): number {
  return text.length * 4 - 1;
}

/** Render text to a Pix with a dark outline (for floating labels). */
export function renderText(text: string, color: RGB, outline: RGB | null = OUTLINE): Pix {
  const t = text.toUpperCase();
  const w = textWidth(t) + 2, h = 7;
  const p = new Pix(w, h);
  let x = 1;
  for (const ch of t) {
    const g = G[ch] ?? G['?'];
    for (let j = 0; j < 5; j++) for (let i = 0; i < 3; i++) {
      if (g[j * 3 + i] === '1') p.set(x + i, 1 + j, color);
    }
    x += 4;
  }
  if (outline) p.outline(outline);
  return p;
}
